import { writeFileSync } from 'fs'
import { join } from 'path'

// Since #704 the reading-widget bundle carries its version in its name, so the
// GitHub Pages site can keep every release's bundle at its root instead of one
// per directory (see scripts/compose-preview-site).
//
// That would break the name three things already point at: samples/reading.html,
// any self-hosted deployment serving `<host>/<version>/scamper-embed.js` -- which
// docs/embedding.md documents as the general form -- and the release directories
// already published. So the build also writes a one-line module under the old
// name that imports the versioned one.
//
// Written with `fs` in `writeBundle` rather than emitted as an asset on purpose:
// inlineCssPlugin fails the build when anything besides the single JS chunk and
// its stylesheets appears in the bundle, which is the check that keeps the
// bundle a single self-contained file. A file on disk beside it is not part of
// that claim -- it holds one `import` and no code of its own.

/**
 * Writes an unversioned alias beside the versioned bundle.
 *
 * @param {{ alias: string, target: () => string }} opts `alias` is the filename
 *        to write, `target` gives the versioned filename to import -- a thunk
 *        because the config's `fileName` is the authority on it.
 * @returns {import('vite').Plugin}
 */
export function embedShimPlugin({ alias, target }) {
  return {
    name: 'embed-shim',
    enforce: 'post',
    writeBundle(options) {
      const versioned = target()
      if (versioned === alias) return
      const note =
        '// Generated by scripts/vite-plugin-embed-shim.mjs. The bundle itself is\n'
      writeFileSync(
        join(options.dir, alias),
        note +
          `// ${versioned}; this keeps the name it used to have working (#704).\n` +
          `import './${versioned}'\n`,
      )
    },
  }
}
